    private void btnProcesarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcesarActionPerformed
                                                 
    try {
        // 1. Capturamos los datos usando los nombres exactos de tus componentes
        String dni = txtDni.getText();
        String nombre = txtNombre.getText();
        String tipoCliente = cmbTipoCliente.getSelectedItem().toString();
        String nacionalidad = cmbNacionalidad.getSelectedItem().toString();
        
        // Si el jatedField5 es el nombre del paquete:
        String nombrePaq = jTextField5.getText(); 
        String fInicio = txtFechaInicio.getText();
        String fFin = txtFechaFin.getText();

        // 2. Creamos el objeto Cliente del Modelo
        Cliente cliente = new Cliente();
        cliente.setDni(dni);
        cliente.setNombreCompleto(nombre);
        cliente.setTipoCliente(tipoCliente);
        cliente.setNacionalidad(nacionalidad);

        // 3. Creamos la lista de productos turísticos vacía
        List<ProductoTuristico> listaProductos = new java.util.ArrayList<>();

        // 4. Llamamos a nuestro ControladorPaquete para calcular precios y guardar
        ControladorPaquete controlador = new ControladorPaquete();
        boolean exito = controlador.registrarYGuardarPaquete(nombrePaq, fInicio, fFin, cliente, listaProductos);

        // 5. Mensaje de resultado
        if (exito) {
            javax.swing.JOptionPane.showMessageDialog(this, "¡Reserva procesada y guardada con éxito!");
            this.dispose(); 
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar la reserva.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }

    } catch (Exception e) {
        e.printStackTrace();
        javax.swing.JOptionPane.showMessageDialog(this, "Ocurrió un error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnProcesarActionPerformed

