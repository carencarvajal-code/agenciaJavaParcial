    private void btnGuardarPaqueteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarPaqueteActionPerformed
        try {
        // 1. Capturar los datos desde las cajas de texto
        String nombre = txtNombrePaquete.getText();
        String fechaIn = txtFechaInicioG.getText(); 
        String fechaF = txtFechaFinG.getText();
        
        // 2. Validar que no estén vacíos
        if (nombre.isEmpty() || fechaIn.isEmpty() || fechaF.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, completa todos los campos obligatorios.");
            return;
        }

        // 3. Crear el cliente para la reserva
        Cliente clienteSeleccionado = new Cliente(); 
        clienteSeleccionado.setNombre("Cliente de Prueba"); // O puedes pedirlo en otra caja de texto
        
        // 4. USAR LA LISTA TEMPORAL CORRECTA (¡Aquí estaba el error del tablaProductos!)
        // Debe ser de tipo ProductoTuristico, tal como lo pide tu ControladorPaquete
        java.util.List<com.mycompany.agencia.modelo.ProductoTuristico> listaProductos = this.listaProductosTemporal;

        // 5. Llamamos al método de tu ControladorPaquete
        boolean exito = controlador.registrarYGuardarPaquete(
                nombre, 
                fechaIn, 
                fechaF, 
                clienteSeleccionado, 
                listaProductos
        );

        // 6. Evaluar la respuesta y mostrar mensaje al usuario
        if (exito) {
            javax.swing.JOptionPane.showMessageDialog(this, "¡Paquete registrado y guardado con éxito!");
            // Limpiar campos
            txtNombrePaquete.setText("");
            txtFechaInicioG.setText("");
            txtFechaFinG.setText("");
            listaProductos.clear(); // Limpiamos la lista temporal
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: No se pudo guardar el paquete en la base de datos.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnGuardarPaqueteActionPerformed

